#!/usr/bin/env python3
"""Reproduce the explicit Unicode 18 L ranges; never promote @missing defaults."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'https://www.unicode.org/Public/18.0.0/ucd/extracted/DerivedBidiClass.txt'
SHA256 = 'd9e23222522551348ea1ccfbb4f62efbf98982afb95840f8959c08ed992c5607'
OUTPUT = ROOT/'crates/jade-pdf-diff/src/strong_ltr_data.rs'


def generate(data):
    """Keep assigned explicit L scalars only, with sorted disjoint ranges."""
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError('Unicode source SHA-256 mismatch')
    ranges = []
    for line in data.decode('utf-8').splitlines():
        body, _, comment = line.partition('#')
        if not body.strip():
            continue
        span, value = body.split(';')
        if value.strip() != 'L' or comment.strip().startswith(('Cn', 'Cs')):
            continue
        bounds = span.strip().split('..')
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        if start <= 0xdfff and end >= 0xd800:
            raise ValueError('Surrogates must not be accepted as scalar evidence')
        ranges.append((start, end))
    merged = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1]:
            raise ValueError('Overlapping Unicode ranges')
        if merged and start == merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], end)
        else:
            merged.append((start, end))
    header = ('// Generated by tools/generate_strong_ltr.py; do not edit.\n'
              '// Copyright © 1991-2026 Unicode, Inc.\n'
              '// Unicode License V3: ../resources/unicode-license-v3.txt\n'
              f'// Source: {SOURCE}\n// SHA-256: {SHA256}\n'
              '/// Unicode 18で明示的にLと定義された、未割当を含まないスカラー区間。\n'
              'pub(super) const RANGES: &[(u32, u32)] = &[\n')
    return header + ''.join(f'    (0x{a:04x}, 0x{b:04x}),\n' for a, b in merged) + '];\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Original hash-pinned DerivedBidiClass.txt')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.source.read_bytes())
    if args.check:
        if OUTPUT.read_text() != result:
            raise SystemExit('Generated strong-LTR table differs')
    else:
        OUTPUT.write_text(result)


if __name__ == '__main__':
    main()
