#!/usr/bin/env python3
"""Reproduce assigned, wide Han/Kana/Common letters from pinned Unicode18 data."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCES={
 'Scripts.txt':'0071fd81b6aeae25f6e8bce8efec3066a6476a91b49bdb2f52dc76e817862a6a',
 'EastAsianWidth.txt':'a0cf29eacd00cfcaec4381c6b7c281685f18dbb4e7ff82b4076ccb342ca839aa',
 'DerivedGeneralCategory.txt':'d6b151d2d40ee9b1876d26f417980f45ffae47b6055ccf7203cb31f07a030f94',
}
OUTPUT=ROOT/'crates/jade-pdf-diff/src/text/japanese_data.rs'
METADATA=ROOT/'crates/jade-pdf-diff/resources/japanese-tracking.json'


def selected(data,accept):
    """Use explicit property lines only, never missing/default values."""
    points=set()
    for line in data.decode('utf-8').splitlines():
        body=line.partition('#')[0].strip()
        if not body:continue
        span,value=map(str.strip,body.split(';'))
        if not accept(value):continue
        bounds=span.split('..');start,end=int(bounds[0],16),int(bounds[-1],16)
        if not 0<=start<=end<=0x10ffff or start<=0xdfff and end>=0xd800:
            raise ValueError('Invalid selected scalar range')
        points.update(range(start,end+1))
    return points


def generate(files):
    """Intersect letter/script/width facts, retaining only four explicit JLReq additions."""
    for name,expected in SOURCES.items():
        if hashlib.sha256(files[name]).hexdigest()!=expected:
            raise ValueError('Unicode source SHA-256 mismatch: '+name)
    scripts=selected(files['Scripts.txt'],lambda v:v in {'Han','Hiragana','Katakana','Common'})
    wide=selected(files['EastAsianWidth.txt'],lambda v:v=='W')
    letters=selected(files['DerivedGeneralCategory.txt'],lambda v:v.startswith('L'))
    points=wide&((scripts&letters)|{0x3007,0x309b,0x309c,0x3013})
    ranges=[]
    for point in sorted(points):
        if ranges and point==ranges[-1][1]+1:ranges[-1]=(ranges[-1][0],point)
        else:ranges.append((point,point))
    header=('// Generated by tools/generate_japanese_letters.py; do not edit.\n'
            '// Copyright © 1991-2026 Unicode, Inc.\n'
            '// Unicode License V3: ../../resources/unicode-license-v3.txt\n'
            '/// Unicode18の明示的な全角Han/Kana等の文字。未割当・ハングル・欧文・通常の約物を除く。\n'
            'pub(super) const RANGES: &[(u32, u32)] = &[\n')
    output=header+''.join(f'    (0x{a:04x}, 0x{b:04x}),\n' for a,b in ranges)+'];\n'
    metadata=dict(unicode_version='18.0.0',sources={
        name:dict(url='https://www.unicode.org/Public/18.0.0/ucd/'+('extracted/' if name=='DerivedGeneralCategory.txt' else '')+name,sha256=sha)
        for name,sha in SOURCES.items()},generator='tools/generate_japanese_letters.py',
        generated='src/text/japanese_data.rs',generated_sha256=hashlib.sha256(output.encode()).hexdigest(),
        ranges=len(ranges),scalars=len(points),license='Unicode License V3',license_file='unicode-license-v3.txt',
        license_sha256=hashlib.sha256((ROOT/'crates/jade-pdf-diff/resources/unicode-license-v3.txt').read_bytes()).hexdigest(),
        tracking_limit_em=0.25,full_em_width_tolerance=0.01,
        typography_source='https://www.w3.org/TR/jlreq/#procedures_for_inter_character_space_expansion',
        class_source='https://github.com/w3c/jlreq/blob/gh-pages/docs/spacing_property/spacing_property.md',
        scope='Assigned EAW=W and General_Category=L* and Script=Han/Hiragana/Katakana/Common, plus U+3007,U+309B,U+309C,U+3013. Used only to distinguish bounded Japanese character tracking from inferred word spaces. JLReq documents up-to-quarter-em inter-character expansion; it does not prescribe PDF text extraction. Literal source blanks, Latin, Hangul and unsupported metrics retain their existing treatment.')
    return output,json.dumps(metadata,ensure_ascii=False,indent=2)+'\n'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source_directory',type=Path)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    result,metadata=generate({name:(args.source_directory/name).read_bytes() for name in SOURCES})
    for path,content in [(OUTPUT,result),(METADATA,metadata)]:
        if args.check:
            if path.read_text()!=content:raise SystemExit('Generated table/metadata differ: '+str(path))
        else:path.write_text(content)


if __name__=='__main__':main()
