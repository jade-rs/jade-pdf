"""固定ReportLabのHelvetica太字glyph幅の数値だけをRustへ生成する。"""
from pathlib import Path
import argparse
import ast
import hashlib
import io
import json
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
META = ROOT / 'crates/jade-pdf2docx-parser/resources/standard-bold-widths.json'
TARGET = ROOT / 'crates/jade-pdf2docx-parser/src/standard_bold_widths.rs'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-archive', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    metadata = json.loads(META.read_text())
    if args.source_archive:
        raw = args.source_archive.read_bytes()
    else:
        with urllib.request.urlopen(metadata['source_archive'], timeout=30) as response:
            raw = response.read(8 * 1024 * 1024 + 1)
    if len(raw) > 8 * 1024 * 1024 or hashlib.sha256(raw).hexdigest() != metadata['source_archive_sha256']:
        raise SystemExit('primary source archive SHA256 mismatch')
    tables = {}
    with tarfile.open(fileobj=io.BytesIO(raw), mode='r:gz') as archive:
        for table in metadata['tables']:
            member = next(m for m in archive.getmembers() if m.name.endswith('/src/reportlab/pdfbase/' + table['file']))
            source = archive.extractfile(member).read()
            if hashlib.sha256(source).hexdigest() != table['sha256']:
                raise SystemExit('primary source table SHA256 mismatch')
            tables[table['file']] = next(ast.literal_eval(n.value) for n in ast.parse(source).body
                                        if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == table['definition'] for t in n.targets))
    names = tables['_fontdata_enc_winansi.py'][32:127]
    widths = [tables['_fontdata_widths_helveticabold.py'][name] for name in names]
    assert widths == [tables['_fontdata_widths_helveticaboldoblique.py'][name] for name in names]
    assert len(widths) == 95 and all(isinstance(w, int) and 0 < w < 2000 for w in widths)
    standard_names = tables['_fontdata_enc_standard.py']
    assert all(tables['_fontdata_widths_helveticabold.py'][standard_names[code]] == 278 for code in [39, 96])
    license_path = META.parent.parent / metadata['license']
    if hashlib.sha256(license_path.read_bytes()).hexdigest() != metadata['license_sha256']:
        raise SystemExit('ReportLab license SHA256 mismatch')
    output = (
        '//! 固定ReportLab4.4.9のHelvetica-Bold/BoldObliqueに共通するASCII advanceのみ。\n'
        '// Copyright (c) 2000-2024, ReportLab Inc.; BSD-3-Clause: ../licenses/reportlab.txt\n'
        '// Provenance: ../resources/standard-bold-widths.json; generated by tools/generate_standard_bold_widths.py.\n\n'
        '/// WinAnsi/MacRomanの印字可能ASCIIに対応する1000 units/emの幅。\n'
        '#[rustfmt::skip]\nconst WIDTHS: [u16; 95] = [\n'
        + ''.join('    ' + ', '.join(map(str, widths[i:i+10])) + ',\n' for i in range(0, 95, 10))
        + '];\n\n'
        '/// 既知の一byte ASCIIだけを読み、StandardEncodingの左右引用符を区別する。\n'
        'pub(super) fn width(code: u8, standard_encoding: bool) -> Option<u16> {\n'
        '    if standard_encoding && matches!(code, 39 | 96) {\n'
        '        return Some(278);\n'
        '    }\n'
        '    WIDTHS.get(usize::from(code.checked_sub(32)?)).copied()\n'
        '}\n'
    )
    if args.check:
        if TARGET.read_text() != output:
            raise SystemExit('generated standard bold widths differ')
    else:
        TARGET.write_text(output)


if __name__ == '__main__':
    main()
